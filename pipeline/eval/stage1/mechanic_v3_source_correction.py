"""Diagnosed publication delivery correction, preserving every original artifact.

A distinct evidence view and publication retain the same frozen author identity.
Only a measured incomplete source delivery permits this independent judgment.
"""
from pathlib import Path
import argparse
import fcntl
import json
import shutil
from . import mechanic_v3_delivery_audit as audit, mechanic_v3_execution as execution
from . import mechanic_v3_revision as revisions, mechanic_v3_outcome_evidence as evidence
from . import mechanic_v3_source_admission as admission, mechanic_v3_full_scope as scope
from .mechanic_v3_runner import read,stamp,exclusive_json,disk,link_tree,configure_cli
from .protocol import sha,dump

VERSION='mechanic-published-source-correction.v1'


def pointer(workspace,identity):
    return Path(workspace)/'engineering/source_publication_corrections'/(identity+'.json')


def verify_claim(value):
    if value.get('version')!=VERSION:raise ValueError('Unknown source correction')
    for path,digest in value['bindings'].items():
        if sha(Path(path))!=digest:raise ValueError('Source correction lineage changed: '+path)
    return value


def diagnose(workspace,identity):
    from .mechanic_v3_cli import parent_workspace
    inventory=scope.load(workspace)
    if identity not in inventory['active_selection']:raise ValueError('Not a frozen selected original')
    selected=workspace if (revisions.publication_dir(workspace)/(identity+'.json')).exists() else parent_workspace(inventory)
    if not selected:raise ValueError('No retained publication to correct')
    receipt=audit.publication(selected,identity)
    if receipt['qualified']:raise ValueError('Valid complete delivery must be skipped, irrespective of score')
    source_defects=[i for t in receipt['tasks'] for i in t['issues'] if i['kind'] in {'TRUNCATED_SOURCE','SOURCE_BYTES_NOT_SUBMITTED','MISSING_SOURCE_IDS'}]
    if not source_defects:raise ValueError('No measured author-source defect; use the appropriate other recovery')
    return receipt,inventory


def prepare(workspace,identity):
    workspace=Path(workspace).resolve();existing=pointer(workspace,identity)
    if existing.exists():
        value=verify_claim(read(existing));return Path(value['correction_workspace']),Path(value['root'])
    diagnosis,inventory=diagnose(workspace,identity)
    origin=Path(diagnosis['root']);original_workspace=Path(diagnosis['workspace'])
    fingerprint=diagnosis['publication_sha256'][:16]
    target=workspace/'source_delivery_corrections'/identity/fingerprint
    root=target/'runs'/identity
    if target.exists():raise ValueError('Incomplete correction retained; inspect before recovery')
    disk(workspace,'published_source_correction',512*1024**2)
    bindings={str(Path(__file__).resolve()):sha(Path(__file__).resolve()),
        str(Path(audit.__file__).resolve()):sha(Path(audit.__file__).resolve()),
        diagnosis['publication']:diagnosis['publication_sha256']}
    old=execution.verify_publication(original_workspace,identity)
    bindings.update(old['bindings'])
    for filename in ['input_manifest.json','source_qualification.json','evidence_manifest.json','sol_plan.json','trace_summary.json']:
        bindings[str(origin/filename)]=sha(origin/filename)
    for p,d in read(origin/'source_qualification.json')['source_bindings'].items():
        if sha(Path(p))!=d:raise ValueError('Original qualified real record changed')
        bindings[p]=d
    case=old['case_id'];folder=revisions.contract_dir(original_workspace,case)
    for file in folder.rglob('*'):
        if file.is_file():bindings[str(file)]=sha(file)
    claim=dict(version=VERSION,time=stamp(),identity=identity,original_publication=diagnosis['publication'],
        parent_score_file=old['score_file'],original_root=str(origin),correction_workspace=str(target),root=str(root),
        scope_binding=inventory['full_scope_binding'],diagnosed_tasks=diagnosis['tasks'],
        reason='Actual scored accepted requests omitted author source; independent full-source judgment on the identical qualified real recording',
        classification='HARNESS_ERROR',product_score=None,scoring_semantics_unchanged=True,
        no_new_recording=True,old_scores_and_publications_preserved=True,bindings=bindings)
    root.mkdir(parents=True)
    dump(target/'diagnosis.json',diagnosis)
    shutil.copy2(original_workspace/'assessment_revision.json',target/'assessment_revision.json')
    link_tree(folder,revisions.contract_dir(target,case))
    link_tree(origin/'input',root/'input');link_tree(origin/'runtime',root/'runtime',runtime=True)
    if (origin/'delivery').exists():link_tree(origin/'delivery',root/'delivery')
    # Original native images only. Derived delivery sheets are regenerated by the
    # existing validated transport, never edited through immutable hard links.
    for file in ['input_manifest.json','sol_plan.json','trace_summary.json','evidence_manifest.json']:
        shutil.copy2(origin/file,root/file)
    # Other manifest channels can live outside input/runtime; retain their exact bytes.
    manifest=read(root/'evidence_manifest.json')
    for item in manifest['items']:
        if item['type']=='frame':continue
        path=Path(item['path'])
        if path.is_absolute() or '..' in path.parts:raise ValueError('Unsafe evidence relative path')
        if not (root/path).exists():
            (root/path).parent.mkdir(parents=True,exist_ok=True)
            shutil.copy2(origin/path,root/path)
    for engine in ['godot','three_js']:
        source=original_workspace/'engineering/native_acceptance'/(engine+'.json')
        if source.exists():
            dest=target/'engineering/native_acceptance'/(engine+'.json');dest.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(source,dest)
    exclusive_json(root/'source_delivery_correction.json',claim)
    qualification=read(origin/'source_qualification.json')
    qualification.update(time=stamp(),new_recording=False,raw_record_reused=True,
        recording='REUSED_HISTORICAL_REAL_RECORD',source_delivery_correction=str(root/'source_delivery_correction.json'),
        notice='按新结果导向契约重新评价历史实录；修复已证明的源码送达缺口；保留旧判词与分数')
    qualification['source_bindings']=dict(qualification['source_bindings'],**bindings)
    qualification['source_bindings'][str(root/'source_delivery_correction.json')]=sha(root/'source_delivery_correction.json')
    dump(root/'source_qualification.json',qualification)
    evidence.freeze(root,read(folder/'frozen.json')['contract_sha256'])
    exclusive_json(existing,claim)
    return target,root


def judge(workspace,identity):
    workspace=Path(workspace).resolve();target,root=prepare(workspace,identity)
    claim=verify_claim(read(pointer(workspace,identity)))
    publication=revisions.publication_dir(target)/(identity+'.json')
    if publication.exists():
        checked=audit.publication(target,identity)
        if not checked['qualified']:raise ValueError('Corrected delivery remains incomplete')
        return checked
    protocol=read(root/'input/pilot_rubric.json');manifest=read(root/'evidence_manifest.json')
    case=read(root/'input_manifest.json')['entry']['case_id'];folder=revisions.contract_dir(target,case)
    contract=read(folder/'contract.json');frozen=read(folder/'frozen.json')
    # Admit/preflight every full request before sending the first model call.
    for task in execution.partitions(protocol,manifest,prefix='mechanic_v3_of1_'):
        name,parent,specs=task
        admission.authorize(root,name,parent)
        if not (root/'model_calls'/name).exists():
            execution.request(root,protocol,manifest,contract,frozen,name,parent,specs)
    row=next(r for r in scope.load(workspace)['entries'] if r['entry']['id']==identity)
    configure_cli(Path(row['source_batch']))
    result=execution.judge_and_publish(target,root,scope.load(workspace))
    checked=audit.publication(target,identity)
    if not checked['qualified']:raise ValueError('Corrected published judgment not delivery qualified')
    dump(target/'real_e2e_acceptance.json',dict(version=VERSION,time=stamp(),status='ACCEPTED',
        original_publication=claim['original_publication'],original_publication_sha256=claim['bindings'][claim['original_publication']],
        correction_publication=checked['publication'],correction_publication_sha256=checked['publication_sha256'],
        complete_source_and_predeclared_frames_delivered=True,old_publication_unchanged=True,
        score=result['score'],audit=checked,production_bindings={str(Path(__file__).resolve()):sha(Path(__file__).resolve())}))
    return checked


def main(argv=None):
    parser=argparse.ArgumentParser();parser.add_argument('--workspace',type=Path,required=True)
    parser.add_argument('--identity',required=True);parser.add_argument('--phase',choices=['prepare','judge'],required=True)
    args=parser.parse_args(argv);workspace=args.workspace.resolve()
    locks=workspace/'locks';locks.mkdir(exist_ok=True)
    with (locks/('outcome_frame_v1_'+args.identity+'.lock')).open('a+') as lock:
        fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
        value=prepare(workspace,args.identity) if args.phase=='prepare' else judge(workspace,args.identity)
    print(json.dumps(dict(identity=args.identity,phase=args.phase,result=value if isinstance(value,dict) else list(map(str,value))),ensure_ascii=False))
    return 0

if __name__=='__main__':raise SystemExit(main())
