def recording_started(root):
    runtime=Path(root)/'runtime'
    return (Path(root)/'native_capture_admission.json').exists() or (runtime.exists() and
        any(p.name!='project' for p in runtime.iterdir()))


def normalize_schedule(protocol, operation):
    """Derive observer metadata only from already declared physical actions.

    Retain the requested endpoint time whenever legal; move it only within the
    original coverage interval. No stability delay, action or window is changed.
    The full original validator, including actual-final-input checks, runs later.
    """
    value=copy.deepcopy(operation);actions=native_actions(operation)
    coverage=(operation['coverage'] if isinstance(operation['coverage'],dict) else
              {row['atom_id']:row for row in operation['coverage']});changes=[]
    for ident, endpoint in value['capture_plan']['endpoints'].items():
        if endpoint['reachability']=='UNREACHABLE':continue
        window=coverage[ident]
        inputs=[a for a in actions if a['probe_id'] in endpoint['probe_ids']
                and ident in a['criterion_ids'] and a['action']!='wait'
                and (not multiclient.enabled(protocol) or a.get('client_role') in {endpoint['client_role'],'BOTH'})
                and window['start_ms']<=a['planned_t_ms']<window['end_ms']]
        if not inputs or endpoint['stable_after_ms']<150 or not endpoint['stable_condition'].strip():
            raise ValueError('No original physical final input/stability metadata for '+ident)
        last=inputs[-1]
        lower=max(window['start_ms'], window['end_ms']-500,
                  last['planned_end_t_ms']+endpoint['stable_after_ms'])
        upper=window['end_ms']-150
        if lower>upper:raise ValueError('Original action/coverage interval has no legal stable endpoint: '+ident)
        wanted={'at_ms':min(max(endpoint['at_ms'],lower),upper),'last_action_id':last['action_id']}
        for key,new in wanted.items():
            if endpoint[key]!=new:
                changes.append(dict(endpoint=ident,field=key,before=endpoint[key],after=new))
                endpoint[key]=new
    return value,changes


def recover_schedule(workspace,row,*,outcome=False):
    """Only a rejected, never-recorded original plan can use this normalization."""
    if outcome and revisions.revision(Path(workspace))!='outcome_frame_v1':
        raise ValueError('Explicit outcome schedule recovery required')
    root=Path(workspace)/'runs'/row['entry']['id']
    failed=root/('model_calls/plan_v3_outcome_frame_v1' if outcome else 'model_calls/plan_v3_fixed_context')
    if recording_started(root) or (root/'sol_plan.json').exists():
        raise ValueError('Schedule metadata recovery is allowed only before recording/acceptance')
    error=read(failed/'validation_error.json')
    if 'endpoint must follow its actual last input' not in error.get('exception',''):
        raise ValueError('Different plan rejection needs a separate repair')
    if (failed/'accepted_response.json').exists() or sha(failed/'response.json')!=error['response_sha256']:
        raise ValueError('Original failed planner response binding changed')
    batch.verify_inputs(root);engine=row['entry']['actual_engine'];proto=core12.verify_attempt(root,engine)
    proof=root/('engineering/outcome_frame_v1_plan_transport' if outcome else 'engineering/initial_fixed_plan_transport')
    raw=read(failed/'response.json');validate_schema(raw,read(failed/'schema.json'))
    corrected,unreachable=normalize_unreachable_conditions(raw,proto)
    corrected,mappings=normalize_source_paths(corrected,root/'input/project')
    expanded=expand(corrected,read(proof/'fixed_context.json'))
    operation,changes=normalize_schedule(proto,expanded)
    if not changes:raise ValueError('No actual schedule metadata correction')
    validate_schema(operation,read(proof/'original_schema.json'))
    operation=batch.validate_operation_plan(root,operation,engine)
    receipt=dict(time=stamp(),classification='NON_SCORING_PRERECORD_OBSERVER_METADATA',
        root_cause='Planner endpoint clock/last_action_id disagrees with its own physical timeline.',
        failed_response_sha256=sha(failed/'response.json'),failure_sha256=sha(failed/'validation_error.json'),
        original_schema_sha256=sha(proof/'original_schema.json'),changes=changes,
        unreachable_expectation_fields=unreachable,unique_sha_source_mappings=mappings,
        actions_unchanged=operation['probes']==raw['probes'],coverage_unchanged=operation['coverage']==batch.decode_plan_coverage(raw)['coverage'],
        full_original_validators=True,recording_not_started=True)
    dest=root/'engineering/prerecord_schedule_metadata';dest.mkdir(parents=True,exist_ok=True)
    exclusive_json(dest/'validated_operation.json',operation)
    receipt['operation_sha256']=sha(dest/'validated_operation.json');exclusive_json(dest/'repair.json',receipt)
    dump(root/'sol_plan.json',operation);endpoint_sparse.freeze_conditions(root,proto,operation)
    write_operation_report(root,operation)
    return root


def recover_capture_map(workspace,row):
    """One fingerprint-derived source-only plan after an actual mapping failure."""
    workspace=Path(workspace).resolve();source=workspace/'runs'/row['entry']['id']
    if recording_started(source) or (source/'sol_plan.json').exists():
        raise ValueError('Mapping recovery requires a never-recorded rejected original plan')
    failed=source/'model_calls/plan_v3_fixed_context';error=read(failed/'validation_error.json')
    exception=error.get('exception','')
    if not any(text in exception for text in ('visual window has no frozen Gameness purpose',
            'endpoint must follow its actual last input')):
        raise ValueError('Different mapping/schedule failure requires a distinct diagnosis')
    if (failed/'accepted_response.json').exists() or sha(failed/'response.json')!=error['response_sha256']:
        raise ValueError('Rejected source response changed')
    batch.verify_inputs(source)
    bindings={str(p.resolve()):sha(p) for folder in ('model_calls/plan_v3_fixed_context','engineering/initial_fixed_plan_transport')
              for p in (source/folder).rglob('*') if p.is_file()}
    bindings[str((source/'input_manifest.json').resolve())]=sha(source/'input_manifest.json')
    fingerprint=hashlib.sha256(json.dumps(bindings,sort_keys=True).encode()).hexdigest()
    recovery_batch=workspace/'plan_recovery'/source.name/fingerprint;root=recovery_batch/'runs'/source.name
    claim=dict(version='whitebox-mechanic-capture-map-recovery.v1',source=str(source),source_bindings=bindings,
        recovery_root=str(root),source_fingerprint=fingerprint,reason='Rejected pre-record plan has a missing mutable observation mapping or an invalid endpoint physical timeline.',
        original_rejection_sha256=sha(failed/'validation_error.json'),original_rejection=exception,
        no_original_attempt_mutation=True,no_runtime_or_scores_in_planner=True)
    claim_path=source/'mechanic_capture_map_recovery_claim.json'
    if claim_path.exists():
        if read(claim_path)!=claim:raise ValueError('Mapping recovery lineage changed')
    else:exclusive_json(claim_path,claim)
    recovery_batch.mkdir(parents=True,exist_ok=True);native.configuration(recovery_batch,workspace)
    disk(recovery_batch,'capture_map_recovery_prepare',2*1024**3)
    if not root.exists():
        root.mkdir(parents=True);link_tree(source/'input',root/'input')
        for name in ('input_manifest.json','attempt_manifest.json'):
            if (source/name).exists():shutil.copy2(source/name,root/name)
        exclusive_json(root/'mechanic_capture_map_recovery.json',dict(claim,claim_sha256=sha(claim_path),time=stamp()))
    saved=read(root/'mechanic_capture_map_recovery.json')
    if saved['claim_sha256']!=sha(claim_path) or saved['source_bindings']!=bindings:raise ValueError('Recovery binding changed')
    batch.verify_inputs(root);engine=row['entry']['actual_engine'];proto=core12.verify_attempt(root,engine)
    folder=revisions.contract_dir(workspace,row['entry']['case_id']);frozen=read(folder/'frozen.json');contract=read(folder/'contract.json')
    if sha(folder/'contract.json')!=frozen['contract_sha256']:raise ValueError('Contract changed')
    if not (root/'sol_plan.json').exists():
        operation=plan_frozen(workspace,root,proto,engine,core12.plan_identity(root,proto,engine),contract,frozen,capture_map_complete=True)
        dump(root/'sol_plan.json',operation);endpoint_sparse.freeze_conditions(root,proto,operation);write_operation_report(root,operation)
    else:batch.validate_operation_plan(root,read(root/'sol_plan.json'),engine)
    return root
