"""Pre-record, source-bound repairs of v3 plan transport and schedule metadata.

Raw responses and original attempts remain immutable. Actions, requirements and
coverage are never generated by metadata normalization. A new source-only plan
is permitted only for a preserved concrete capture-map transport rejection.
"""
from pathlib import Path
